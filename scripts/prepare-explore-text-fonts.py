"""Build pinned, OFL-licensed static faces shared by browser and worker.

Preparation only: pip install fonttools brotli, then run this script.
Runtime rendering has no Python or Google Fonts network dependency.
"""
import hashlib
import io
import json
import pathlib
import urllib.request
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
REVISION = "1d0e46c7933245c8180fe83e47917961c913bbdb"
SOURCES = {
    "inter": ("Inter", "Inter[opsz,wght].ttf"),
    "dmsans": ("DM Sans", "DMSans[opsz,wght].ttf"),
    "robotocondensed": ("Roboto Condensed", "RobotoCondensed[wght].ttf"),
    "montserrat": ("Montserrat", "Montserrat[wght].ttf"),
}
DEST = ROOT / "worker/src/assets/fonts/explore-text"
PUBLIC = ROOT / "public/explore-text-fonts"
DEST.mkdir(parents=True, exist_ok=True)
PUBLIC.mkdir(parents=True, exist_ok=True)
metrics, manifest, css = {}, {"revision": REVISION, "files": {}}, []

def fetch(relative):
    url = f"https://raw.githubusercontent.com/google/fonts/{REVISION}/ofl/{relative}"
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "UGCPilot-font-build"}), timeout=60).read()

for font_id, (label, filename) in SOURCES.items():
    raw = fetch(f"{font_id}/{urllib.parse.quote(filename)}")
    license_bytes = fetch(f"{font_id}/OFL.txt")
    (DEST / f"{font_id}-OFL.txt").write_bytes(license_bytes)
    (PUBLIC / f"{font_id}-OFL.txt").write_bytes(license_bytes)
    manifest["files"][font_id] = {"source": filename, "sourceSha256": hashlib.sha256(raw).hexdigest(), "weights": {}}
    for weight, style in [(400, "Regular"), (500, "Medium"), (700, "Bold")]:
        variable = TTFont(io.BytesIO(raw), recalcTimestamp=False)
        axes = {axis.axisTag: axis.defaultValue for axis in variable["fvar"].axes}
        axes["wght"] = weight
        font = instantiateVariableFont(variable, axes, inplace=True)
        # A unique internal family avoids host/other-workflow font substitution.
        family = f"UGCExplore{label.replace(' ', '')}W{weight}"
        names = {1: family, 2: style, 3: f"{family} 1.0", 4: family, 6: family.replace(" ", ""), 16: family, 17: style}
        for record in font["name"].names:
            if record.nameID in names:
                record.string = names[record.nameID].encode(record.getEncoding())
        file_base = f"{font_id}-{weight}"
        ttf_path = DEST / f"{file_base}.ttf"
        font.save(ttf_path)
        cmap, hmtx, upm = font.getBestCmap(), font["hmtx"].metrics, font["head"].unitsPerEm
        # Compact Latin/Greek/Cyrillic and punctuation metrics. Other scripts use
        # the existing conservative fallback; no user characters are dropped.
        widths = {chr(cp): round(hmtx[glyph][0] / upm, 5) for cp, glyph in cmap.items()
                  if 32 <= cp <= 0x52F or 0x2000 <= cp <= 0x206F}
        metrics[file_base] = widths
        font.flavor = "woff2"
        woff_path = PUBLIC / f"{file_base}.woff2"
        font.save(woff_path)
        css.append(f'@font-face {{ font-family: "{family}"; src: url("/explore-text-fonts/{file_base}.woff2") format("woff2"); font-style: normal; font-weight: {weight}; font-display: swap; }}')
        manifest["files"][font_id]["weights"][str(weight)] = {
            "family": family, "ttfSha256": hashlib.sha256(ttf_path.read_bytes()).hexdigest(),
            "woff2Sha256": hashlib.sha256(woff_path.read_bytes()).hexdigest(),
        }
    print(f"Prepared {label}", flush=True)

(ROOT / "worker/src/lib/explore-text-font-metrics.json").write_text(json.dumps(metrics, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
(DEST / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
(ROOT / "components/explore/explore-text-fonts.css").write_text("/* Generated by scripts/prepare-explore-text-fonts.py. Loaded only by video text UI. */\n" + "\n".join(css) + "\n", encoding="utf-8")
